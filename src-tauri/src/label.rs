//! 盒子名字的颜色自适应：看一眼盒子**四周**的壁纸有多亮，决定名字用白字还是深色字。
//!
//! 为什么需要：盒子没有底板（截图贴图那套已经删了），名字直接压在壁纸上。
//! 白字 + 深色描边在深色壁纸 / 照片上很好，但浅色壁纸（尤其接近纯白）上
//! 白字和背景一样亮，只剩一圈模糊的深色描边 —— 12px 字号下就是一团灰。
//! 桌面图标是同一问题的官方解法：**字色跟着壁纸亮度走**（浅壁纸用黑字）。
//! 这里照抄这个思路。
//!
//! 为什么不去读壁纸文件自己算：壁纸可能是幻灯片放映、要按「填充 / 平铺 / 跨屏」
//! 换算，还要解码 PNG/JPEG —— 本项目不引第三方依赖，为一个字色拉一个图像解码库
//! 不划算。直接读**屏幕像素**更省事，而且读到的就是用户眼睛看到的那块背景
//! （取色器 `pick::pixel_at` 已经在用同一套 GetDC + GetPixel）。
//!
//! 局限（都可以接受）：
//!  - 采样点只能落在盒子**外面**：盒子覆盖的地方读到的就是自己的像素。
//!    壁纸是大渐变或照片时，盒子边缘和外面的亮度可能不同 —— 所以取一圈多点、
//!    用中位数抵抗个别点落在桌面图标 / 别的盒子文字上。
//!  - 盒子被别的窗口挡住时，读到的是那个窗口的像素。但那时盒子本身也被挡住，
//!    名字根本看不见，判错也没人察觉。
use crate::pick;
use crate::Rect;

/// 一个物理像素的亮度（0~255）。权重按人眼对 RGB 的敏感度（Rec.709），
/// 比简单的 `(r+g+b)/3` 更贴近「白不白」的观感 —— 纯蓝 (#0000FF) 平均下来是 85，
/// 看着却是很深的颜色，用加权算出来只有 18。
fn luma_at(x: i32, y: i32) -> Option<i32> {
    pick::pixel_at(x, y)
        .map(|(r, g, b)| (2126 * r as i32 + 7152 * g as i32 + 722 * b as i32) / 10000)
}

/// 盒子四周的采样点（屏幕物理像素坐标）。
///
/// 名字在盒子**下半部分**，所以靠近下面的点给得多一些：壁纸常有上浅下深的变化，
/// 名字实际压的那块背景才是要判断的。
fn sample_points(r: &Rect) -> Vec<(i32, i32)> {
    let (l, t) = (r.x, r.y);
    let (rt, b) = (r.x + r.w, r.y + r.h);
    let cx = r.x + r.w / 2;
    let cy = r.y + r.h / 2;
    // 离边框的距离：约 12% 边长，最少 6px（100% 缩放下 80px 的盒子 = 9px）。
    // 太近会吃到自己窗口边缘的抗锯齿像素，太远就跑到别人的地盘上了。
    let d = ((r.w.min(r.h) as f64 * 0.12) as i32).max(6);
    let d2 = d * 3;
    let q = (r.w / 4).max(4);
    vec![
        // 正下方（名字正对着的位置）
        (cx, b + d),
        (cx - q, b + d),
        (cx + q, b + d),
        (cx, b + d2),
        (cx - q, b + d2),
        (cx + q, b + d2),
        // 左右
        (l - d, b + d),
        (rt + d, b + d),
        (l - d, cy),
        (rt + d, cy),
        // 上方
        (cx, t - d),
        (l - d, t - d),
        (rt + d, t - d),
        // 远处一圈兜底
        (l - d2, cy),
        (rt + d2, cy),
        (cx, t - d2),
    ]
}

/// 盒子附近的背景亮度，0.0（纯黑）~ 1.0（纯白）。
///
/// 取不到足够多的点就返回 None（窗口刚销毁 / 点全在屏幕外），
/// 前端保持上一次的判断，不要来回闪。
pub fn bg_luma(r: &Rect) -> Option<f64> {
    let mut v: Vec<i32> = Vec::new();
    for (x, y) in sample_points(r) {
        if let Some(l) = luma_at(x, y) {
            v.push(l);
        }
    }
    if v.is_empty() {
        return None;
    }
    v.sort_unstable();
    // 中位数：个别点落在桌面图标的白字 / 别的盒子名字上也不至于翻车
    Some(v[v.len() / 2] as f64 / 255.0)
}
